def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    existing = {row["title"] for row in query("SELECT title FROM kb_entry")}
    inserted, skipped = 0, 0
    for item in SEED:
        if item["title"] in existing:
            skipped += 1
            continue
        if args.dry_run:
            print(f"[dry-run] 会插入：{item['topic']} / {item['title']}")
            inserted += 1
            continue
        execute(
            "INSERT INTO kb_entry (topic, title, keywords, body, priority, enabled, created_by, updated_by) "
            "VALUES (%s, %s, %s, %s, %s, 1, 'seed', 'seed')",
            (item["topic"], item["title"], item["keywords"], item["body"], item["priority"]),
        )
        inserted += 1
    print(f"种子条目：插入 {inserted} 条，已存在跳过 {skipped} 条。")
    if inserted and not args.dry_run:
        print("桥接最多 60 秒内自动生效（无需重启）。")


if __name__ == "__main__":
    main()
